/**
 * Where each school IS — the campus town, not the stadium.
 *
 * NOT IN THE SAVE, and that is checked rather than assumed. `Team` carries both
 * a `City` and a `Stadium` reference, so the game clearly models this, but on a
 * real dynasty save the `City` table has capacity 32 and ZERO populated rows
 * (`Stadium`: 183 and zero), and both resolve to nothing for all 143 team rows.
 * The strings live in a catalogue outside the save, like the AD contract-goal
 * wording. So this is authored reference data.
 *
 * DELIBERATELY SEPARATE FROM `stadiumData.ts`, which also has a city — they
 * answer different questions and must not be merged. That one is where a team
 * PLAYS; this one is where the school IS. Measured across the 138 FBS programs,
 * they disagree on six, and the differences are not trivial:
 *
 *   UCLA            plays Pasadena, CA        is Los Angeles, CA
 *   Miami           plays Miami Gardens, FL   is Coral Gables, FL
 *   UNLV            plays Paradise, NV        is Las Vegas, NV
 *   UConn           plays East Hartford, CT   is Storrs, CT
 *   Air Force       plays Colorado Springs    is USAF Academy
 *   Boston College  plays Boston, MA          is Chestnut Hill, MA
 *
 * A masthead reading "UCLA — Pasadena, CA" is simply wrong, which is why the
 * stadium table cannot serve this purpose. Use `stadiumData` for venues and
 * this for identity.
 *
 * KEYED ON `canonicalKey`, the same identity logos and stadium data already
 * use, so a lookup by any in-game DisplayName resolves exactly as a logo does —
 * aliases ("App St." -> appalachianstate) included. Generated by running the
 * app's own normaliser over the 138 FBS teams in a real save, not hand-typed:
 * 138 entries, 138 distinct keys, no collisions.
 *
 * WATCH OUT — all real, all easy to get wrong:
 *   - Miami (OH) is in OXFORD, OHIO. Not Miami, not Florida.
 *   - Jax State is Jacksonville, ALABAMA. Not Florida.
 *   - Bowling Green is Ohio; W. Kentucky is in Bowling Green, KENTUCKY.
 *   - Missouri State is Springfield, MISSOURI.
 *   - Columbia is both South Carolina and Missouri; Athens is both Georgia and
 *     Ohio; Oxford is both Mississippi and Ohio.
 */

export interface SchoolLocation {
  /** The campus town. */
  city: string;
  /** Full state name, matching the spelling the save uses for player `homeState`. */
  state: string;
  /** USPS two-letter code — what a masthead wants. */
  stateCode: string;
  /**
   * The recognisable city, where the campus town isn't it. Absent when `city`
   * is already the well-known name. Prefer this for anything pictorial: nobody
   * has a mental image of "University Park, PA", but everyone has one of State
   * College. 17 of 138 need it.
   */
  metro?: string;
}

