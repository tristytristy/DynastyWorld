/**
 * Where a school is, or undefined if it isn't one we know.
 *
 * Undefined is a real answer: a TeamBuilder import or roster mod can carry a
 * name that was never in EA's list, and inventing a location for it would be
 * worse than showing nothing.
 */
export function schoolLocation(teamName: string | null | undefined): SchoolLocation | undefined {
  if (!teamName) return undefined;
  return SCHOOL_LOCATIONS[canonicalKey(teamName)];
}

/**
 * "Los Angeles, CA" — the masthead label. Null when unknown, so a caller
 * renders nothing rather than a stray comma.
 *
 * `preferMetro` swaps in the recognisable city; leave it off for anything
 * factual (this school is in Chestnut Hill) and turn it on for anything
 * pictorial (this is a picture of Boston).
 */
export function schoolLocationLabel(
  teamName: string | null | undefined,
  opts?: { full?: boolean; preferMetro?: boolean },
): string | null {
  const found = schoolLocation(teamName);
  if (!found) return null;
  const place = opts?.preferMetro ? (found.metro ?? found.city) : found.city;
  return `${place}, ${opts?.full ? found.state : found.stateCode}`;
}

/**
 * Extra words a team dropdown should match on, beyond the display name.
 *
 * EA abbreviates: "App St.", "Jax State", "C. Michigan", "Middle Tenn". Someone
 * searching a 138-row dropdown types the name they know, which is usually the
 * long one — so without this, "Appalachian" finds nothing. The city is included
 * too, since "Boone" or "Ann Arbor" is how some people think of a program.
 *
 * Kept here rather than hand-written per call site because this module already
 * holds the one authoritative city per school, and `canonicalKey` already
 * resolves the abbreviations — so both halves are data the app maintains anyway.
 */
export function expandTeamSearchTerms(teamName: string): string {
  const found = schoolLocation(teamName);
  const words = [
    teamName.replace(/\bSt\.\b/g, 'State'),
    teamName.replace(/^C\.\s/, 'Central ').replace(/^E\.\s/, 'Eastern ').replace(/^W\.\s/, 'Western ').replace(/^N\.\s/, 'Northern ').replace(/^S\.\s/, 'Southern '),
    found?.city ?? '',
    found?.metro ?? '',
    found?.state ?? '',
  ];
  return [...new Set(words.filter(Boolean))].join(' ');
}
